import type { AstroIntegration, AstroIntegrationLogger } from "astro";
import type { ResolvedConfig } from "vite";

import * as fs from "node:fs/promises";
import * as path from "node:path";
import { fileURLToPath } from "node:url";
import { preprocessCSS, resolveConfig } from "vite";

export interface CSSModuleTypesOptions {
	/**
	 * Directories to look for CSS modules in, relative to the project root.
	 * @default [srcDir] (`["src"]` unless Astro's `srcDir` is changed)
	 */
	directories?: string[];
}

// The same file extensions Vite treats as CSS modules
// cspell:ignore pcss styl
const cssModulePattern =
	/\.module\.(?:css|less|sass|scss|styl|stylus|pcss|postcss|sss)$/;
const generatedMarker = "// Generated by astro-css-module-types";

/**
 * Writes a `.d.ts` next to each CSS module that lists its class names,
 * so typos in them fail type checking.
 * Runs in `astro sync`, `astro check`, `astro build`, and `astro dev`,
 * and updates them as CSS modules are added, changed, or deleted in `astro dev`.
 * @param options Which directories to look for CSS modules in.
 * @returns An Astro integration.
 */
export function cssModuleTypes(
	options: CSSModuleTypesOptions = {},
): AstroIntegration {
	let command: string | undefined;
	let directories: string[] = [];
	let viteConfig: ResolvedConfig | undefined;

	const queues = new Map<string, Promise<void>>();

	const isWatched = (file: string) =>
		cssModulePattern.test(file) &&
		directories.some((directory) => isWithin(directory, file));

	const update = async (file: string) => {
		if (!viteConfig) {
			return;
		}

		let code: string;
		try {
			code = await fs.readFile(file, "utf8");
		} catch (error) {
			if (isNotFound(error)) {
				await removeGenerated(`${file}.d.ts`);
				return;
			}

			throw error;
		}

		// The same preprocessing and CSS modules options Vite uses for its imports
		const { modules } = await preprocessCSS(code, file, viteConfig);
		if (modules) {
			await writeIfChanged(
				`${file}.d.ts`,
				printDeclarations(path.basename(file), Object.keys(modules)),
			);
		} else {
			await removeGenerated(`${file}.d.ts`);
		}
	};

	// One at a time per file, so a slow earlier update can't overwrite a newer one
	const queue = (file: string, logger: AstroIntegrationLogger) => {
		const next = (queues.get(file) ?? Promise.resolve())
			.then(() => update(file))
			.catch((error: unknown) => {
				logger.warn(
					`Couldn't generate types for ${path.relative(process.cwd(), file)}: ${String(error)}`,
				);
			});

		queues.set(file, next);
		return next;
	};

	return {
		hooks: {
			"astro:config:done": async ({ config, logger }) => {
				if (command === "preview") {
					return;
				}

				const root = fileURLToPath(config.root);
				directories = options.directories
					? options.directories.map((directory) =>
							path.resolve(root, directory),
						)
					: [fileURLToPath(config.srcDir)];
				viteConfig = await resolveConfig(
					{
						configFile: false,
						css: config.vite.css,
						logLevel: "silent",
						resolve: config.vite.resolve,
						root,
					},
					"build",
				);

				const files = (
					await Promise.all(directories.map((directory) => walk(directory)))
				).flat();
				const sources = new Set(files.filter(isWatched));

				// Declarations whose CSS modules were deleted, renamed, or are on another branch
				const orphans = files.filter(
					(file) =>
						file.endsWith(".d.ts") &&
						cssModulePattern.test(file.slice(0, -".d.ts".length)) &&
						!sources.has(file.slice(0, -".d.ts".length)),
				);

				const results = await Promise.allSettled([
					...[...sources].map(update),
					...orphans.map(removeGenerated),
				]);
				const errors = results.flatMap((result) =>
					result.status === "rejected" ? [result.reason as unknown] : [],
				);

				if (errors.length) {
					const message = `Couldn't generate CSS module types:\n${errors.map(String).join("\n")}`;

					// The dev server shows CSS errors itself, so it shouldn't stop starting
					if (command === "dev") {
						logger.warn(message);
					} else {
						throw new Error(message);
					}
				}
			},
			"astro:config:setup": (params) => {
				command = params.command;
			},
			"astro:server:setup": ({ logger, server }) => {
				server.watcher.on("all", (event, file) => {
					if (
						(event === "add" || event === "change" || event === "unlink") &&
						isWatched(file)
					) {
						void queue(file, logger);
					}
				});
			},
		},
		name: "astro-css-module-types",
	};
}

function isNotFound(error: unknown) {
	return (
		error instanceof Error && (error as NodeJS.ErrnoException).code === "ENOENT"
	);
}

function isWithin(directory: string, file: string) {
	const relative = path.relative(directory, file);
	return !!relative && !relative.startsWith("..") && !path.isAbsolute(relative);
}

function printDeclarations(fileName: string, classNames: string[]) {
	return [
		`${generatedMarker} from ${fileName}.`,
		"declare const styles: {",
		...classNames.map(
			(className) =>
				`\treadonly ${/^[$_a-z][\w$]*$/i.test(className) ? className : JSON.stringify(className)}: string;`,
		),
		"};",
		"",
		"export default styles;",
		"",
	].join("\n");
}

/** Removes a declaration file only if this integration generated it. */
async function removeGenerated(file: string) {
	try {
		if ((await fs.readFile(file, "utf8")).startsWith(generatedMarker)) {
			await fs.rm(file);
		}
	} catch (error) {
		if (!isNotFound(error)) {
			throw error;
		}
	}
}

async function walk(directory: string): Promise<string[]> {
	let entries;
	try {
		entries = await fs.readdir(directory, { withFileTypes: true });
	} catch (error) {
		if (isNotFound(error)) {
			return [];
		}

		throw error;
	}

	const files = await Promise.all(
		entries.map(async (entry) => {
			const entryPath = path.join(directory, entry.name);

			if (!entry.isDirectory()) {
				return [entryPath];
			}

			return entry.name === "node_modules" || entry.name.startsWith(".")
				? []
				: walk(entryPath);
		}),
	);

	return files.flat();
}

/** Writes a declaration file if it changed, refusing to replace one this integration didn't generate. */
async function writeIfChanged(file: string, contents: string) {
	try {
		const existing = await fs.readFile(file, "utf8");
		if (existing === contents) {
			return;
		}

		if (!existing.startsWith(generatedMarker)) {
			throw new Error(
				`${file} wasn't generated by astro-css-module-types. Delete it to have it generated.`,
			);
		}
	} catch (error) {
		if (!isNotFound(error)) {
			throw error;
		}
	}

	await fs.writeFile(file, contents);
}
