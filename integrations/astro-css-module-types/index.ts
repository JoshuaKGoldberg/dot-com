import type { AstroIntegration, AstroIntegrationLogger } from "astro";
import type { ResolvedConfig } from "vite";

import * as fs from "node:fs/promises";
import * as path from "node:path";
import { fileURLToPath } from "node:url";
import { preprocessCSS, resolveConfig } from "vite";

export interface CSSModuleTypesOptions {
	/**
	 * Directories to look for CSS modules in, relative to the project root.
	 * @default [srcDir] (`["src"]` unless Astro's `srcDir` is changed)
	 */
	directories?: string[];
}

// The same file extensions Vite treats as CSS modules
// cspell:ignore pcss styl
const cssModuleExtensions = [
	"css",
	"less",
	"sass",
	"scss",
	"styl",
	"stylus",
	"pcss",
	"postcss",
	"sss",
];
const cssModulePattern = new RegExp(
	`\\.module\\.(?:${cssModuleExtensions.join("|")})$`,
);
const stylesheetPattern = new RegExp(
	`\\.(?:${cssModuleExtensions.join("|")})$`,
);
const generatedMarker = "// Generated by astro-css-module-types";

/**
 * Writes a `.d.ts` next to each CSS module that lists its class names,
 * so typos in them fail type checking.
 * Runs in `astro sync`, `astro check`, `astro build`, and `astro dev`,
 * and updates them as CSS modules are added, changed, or deleted in `astro dev`.
 * @param options Which directories to look for CSS modules in.
 * @returns An Astro integration.
 */
export function cssModuleTypes(
	options: CSSModuleTypesOptions = {},
): AstroIntegration {
	let command: string | undefined;
	let directories: string[] = [];
	let pagesDirectory: string | undefined;
	let resolveViteConfig: (() => Promise<ResolvedConfig>) | undefined;
	let viteConfig: ResolvedConfig | undefined;

	const queues = new Map<string, Promise<void>>();

	// Files each CSS module @imports, so dev can update it when they change
	const dependencies = new Map<string, Set<string>>();

	// CSS modules whose last update failed, such as by @importing a file that doesn't exist yet,
	// and their last error, so repeated failures aren't logged again
	const failed = new Map<string, string>();
	let retrying = false;
	let retryAgain = false;

	// Vite's resolver remembers files that didn't exist, so adding or deleting a stylesheet
	// means the next update needs a fresh config, and failures that saw an older one need retrying
	let configRefresh: Promise<ResolvedConfig> | undefined;
	let configStale = false;
	let stylesheetEvents = 0;

	const getViteConfig = async () => {
		if (configStale && resolveViteConfig) {
			configStale = false;
			const refresh: Promise<ResolvedConfig> = resolveViteConfig().then(
				(refreshed) => {
					// A slower, older refresh shouldn't replace a newer one
					if (configRefresh === refresh) {
						viteConfig = refreshed;
					}

					return refreshed;
				},
				(error: unknown) => {
					configStale = true;
					throw error;
				},
			);
			configRefresh = refresh;
		}

		return configRefresh ? await configRefresh : viteConfig;
	};

	const isWatched = (file: string) =>
		cssModulePattern.test(file) &&
		directories.some(
			(directory) =>
				isWithin(directory, file) &&
				!path
					.relative(directory, file)
					.split(path.sep)
					.slice(0, -1)
					.some((part) => part === "node_modules" || part.startsWith(".")),
		);

	// Astro would treat a .d.ts in src/pages as an endpoint, unless a part of its path starts with _ or .
	const isRoute = (file: string) =>
		!!pagesDirectory &&
		isWithin(pagesDirectory, file) &&
		!path
			.relative(pagesDirectory, file)
			.split(path.sep)
			.some((part) => part.startsWith("_") || part.startsWith("."));

	const update = async (file: string) => {
		let code: string;
		try {
			code = await fs.readFile(file, "utf8");
		} catch (error) {
			if (isNotFound(error)) {
				dependencies.delete(file);
				failed.delete(file);
				await removeGenerated(`${file}.d.ts`);
				return;
			}

			throw error;
		}

		if (isRoute(file)) {
			await removeGenerated(`${file}.d.ts`);
			throw new Error(
				"It's in the pages directory, where Astro would make its .d.ts a route. Move it, or start its name or a directory's name with _.",
			);
		}

		const config = await getViteConfig();
		if (!config) {
			return;
		}

		// The same preprocessing and CSS modules options Vite uses for its imports
		const { deps, modules } = await preprocessCSS(code, file, config);
		dependencies.set(
			file,
			new Set([...(deps ?? [])].map((dep) => path.resolve(dep))),
		);

		if (modules) {
			await writeIfChanged(
				`${file}.d.ts`,
				printDeclarations(path.basename(file), Object.keys(modules)),
			);
		} else {
			await removeGenerated(`${file}.d.ts`);
		}
	};

	// One at a time per file, so a slow earlier update can't overwrite a newer one
	const queue = (file: string, logger: AstroIntegrationLogger) => {
		let eventsBefore = stylesheetEvents;
		const next = (queues.get(file) ?? Promise.resolve())
			.then(async () => {
				eventsBefore = stylesheetEvents;
				await update(file);
				failed.delete(file);
			})
			.catch((error: unknown) => {
				const message = errorMessage(error);
				if (failed.get(file) !== message) {
					logger.warn(
						`Couldn't generate types for ${path.relative(process.cwd(), file)}: ${message}`,
					);
				}

				failed.set(file, message);

				// A stylesheet appeared or disappeared during the update, which might fix it
				if (stylesheetEvents !== eventsBefore) {
					retryFailed(logger);
				}
			});

		queues.set(file, next);
		void next.then(() => {
			if (queues.get(file) === next) {
				queues.delete(file);
			}
		});

		return next;
	};

	// Only one retry of failed CSS modules runs at a time, with one more after it if stylesheets changed meanwhile
	const retryFailed = (logger: AstroIntegrationLogger) => {
		if (!failed.size) {
			return;
		}

		if (retrying) {
			retryAgain = true;
			return;
		}

		retrying = true;
		Promise.all([...failed.keys()].map((cssModule) => queue(cssModule, logger)))
			.catch((error: unknown) => {
				logger.warn(`Couldn't retry generating types: ${String(error)}`);
			})
			.finally(() => {
				retrying = false;
				if (retryAgain) {
					retryAgain = false;
					retryFailed(logger);
				}
			});
	};

	return {
		hooks: {
			"astro:config:done": async ({ config, injectTypes, logger }) => {
				if (command === "preview") {
					return;
				}

				// Relative imports of CSS modules without generated types would otherwise silently
				// get astro/client's loose *.module.css types, as these longer patterns take precedence
				injectTypes({
					content: printMissingDeclarations(),
					filename: "missing-css-module-types.d.ts",
				});

				const root = fileURLToPath(config.root);
				directories = options.directories
					? options.directories.map((directory) =>
							path.resolve(root, directory),
						)
					: [fileURLToPath(config.srcDir)];
				resolveViteConfig = () =>
					resolveConfig(
						{
							configFile: false,
							css: config.vite.css,
							logLevel: "silent",
							resolve: config.vite.resolve,
							root,
						},
						"build",
					);
				viteConfig = await resolveViteConfig();

				const files = (
					await Promise.all(directories.map((directory) => walk(directory)))
				).flat();
				const sources = new Set(files.filter(isWatched));

				// Declarations whose CSS modules were deleted, renamed, or are on another branch
				const orphans = files.filter(
					(file) =>
						file.endsWith(".d.ts") &&
						cssModulePattern.test(file.slice(0, -".d.ts".length)) &&
						!sources.has(file.slice(0, -".d.ts".length)),
				);

				const results = await Promise.allSettled([
					...[...sources].map((file) =>
						update(file).catch((error: unknown) => {
							failed.set(file, errorMessage(error));
							throw new Error(
								`${path.relative(process.cwd(), file)}: ${errorMessage(error)}`,
								{ cause: error },
							);
						}),
					),
					...orphans.map(removeGenerated),
				]);
				const errors = results.flatMap((result) =>
					result.status === "rejected" ? [result.reason as unknown] : [],
				);

				if (errors.length) {
					const message = `Couldn't generate CSS module types:\n${errors.map(errorMessage).join("\n")}`;

					// Only fail type checking, as dev and build report CSS errors themselves
					if (command === "sync") {
						throw new Error(message);
					}

					logger.warn(message);
				}
			},
			"astro:config:setup": async (params) => {
				command = params.command;
				if (command === "preview") {
					return;
				}

				pagesDirectory = path.join(
					fileURLToPath(params.config.srcDir),
					"pages",
				);

				// Builds find routes before astro:config:done, so stale ones need removing first
				const routes = (await walk(pagesDirectory)).filter(
					(file) =>
						file.endsWith(".d.ts") &&
						cssModulePattern.test(file.slice(0, -".d.ts".length)) &&
						isRoute(file),
				);
				await Promise.all(routes.map(removeGenerated));
			},
			"astro:server:setup": ({ logger, server }) => {
				server.watcher.on("all", (event, file) => {
					if (event !== "add" && event !== "change" && event !== "unlink") {
						return;
					}

					if (isWatched(file)) {
						void queue(file, logger);
					}

					// A deleted declaration file, such as a hand-written one, should be regenerated
					if (
						event === "unlink" &&
						file.endsWith(".d.ts") &&
						isWatched(file.slice(0, -".d.ts".length))
					) {
						void queue(file.slice(0, -".d.ts".length), logger);
					}

					// An added, fixed, or deleted stylesheet might be what a failed CSS module needed
					if (stylesheetPattern.test(file)) {
						if (event !== "change") {
							configStale = true;
							stylesheetEvents += 1;
						}

						retryFailed(logger);
					}

					for (const [cssModule, deps] of dependencies) {
						if (deps.has(path.resolve(file))) {
							void queue(cssModule, logger);
						}
					}
				});
			},
		},
		name: "astro-css-module-types",
	};
}

function errorMessage(error: unknown) {
	return error instanceof Error ? error.message : String(error);
}

function isNotFound(error: unknown) {
	return (
		error instanceof Error && (error as NodeJS.ErrnoException).code === "ENOENT"
	);
}

function isWithin(directory: string, file: string) {
	const relative = path.relative(directory, file);
	return (
		!!relative &&
		relative !== ".." &&
		!relative.startsWith(`..${path.sep}`) &&
		!path.isAbsolute(relative)
	);
}

function printDeclarations(fileName: string, classNames: string[]) {
	return [
		`${generatedMarker} from ${fileName}.`,
		"declare const styles: {",
		...classNames.map(
			(className) =>
				`\treadonly ${/^[$_a-z][\w$]*$/i.test(className) ? className : JSON.stringify(className)}: string;`,
		),
		"};",
		"",
		"export default styles;",
		"",
	].join("\n");
}

function printMissingDeclarations() {
	return cssModuleExtensions
		.flatMap((extension) =>
			["./", "../"].map((prefix) =>
				[
					`declare module "${prefix}*.module.${extension}" {`,
					'\tconst styles: { readonly "No generated types: check that this CSS module exists, then run astro sync": never };',
					"\texport default styles;",
					"}",
				].join("\n"),
			),
		)
		.join("\n\n");
}

/** Removes a declaration file only if this integration generated it. */
async function removeGenerated(file: string) {
	try {
		if ((await fs.readFile(file, "utf8")).startsWith(generatedMarker)) {
			await fs.rm(file);
		}
	} catch (error) {
		if (!isNotFound(error)) {
			throw error;
		}
	}
}

async function walk(directory: string): Promise<string[]> {
	let entries;
	try {
		entries = await fs.readdir(directory, { withFileTypes: true });
	} catch (error) {
		if (isNotFound(error)) {
			return [];
		}

		throw error;
	}

	const files = await Promise.all(
		entries.map(async (entry) => {
			const entryPath = path.join(directory, entry.name);

			if (!entry.isDirectory()) {
				return [entryPath];
			}

			return entry.name === "node_modules" || entry.name.startsWith(".")
				? []
				: walk(entryPath);
		}),
	);

	return files.flat();
}

/** Writes a declaration file if it changed, refusing to replace one this integration didn't generate. */
async function writeIfChanged(file: string, contents: string) {
	try {
		const existing = await fs.readFile(file, "utf8");
		if (existing === contents) {
			return;
		}

		if (!existing.startsWith(generatedMarker)) {
			throw new Error(
				`${file} wasn't generated by astro-css-module-types. Delete it to have it generated.`,
			);
		}
	} catch (error) {
		if (!isNotFound(error)) {
			throw error;
		}
	}

	await fs.writeFile(file, contents);
}
